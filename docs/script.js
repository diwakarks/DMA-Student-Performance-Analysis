// GPA Prediction Simulator
function setupPredictor() {
  const studySlider = document.getElementById("predStudyHours");
  const prevSgpaSlider = document.getElementById("predPrevSgpa");
  const backlogsSlider = document.getElementById("predBacklogs");

  function calcPrediction() {
    const study = parseFloat(studySlider.value);
    const prev = parseFloat(prevSgpaSlider.value);
    const back = parseFloat(backlogsSlider.value);

    document.getElementById("valStudyHours").textContent = study.toFixed(1) + " hrs/day";
    document.getElementById("valPrevSgpa").textContent = prev.toFixed(2);
    document.getElementById("valBacklogs").textContent = back + " active";

    // OLS Formula: SGPA = 5.2459 + 0.2797*(study) + 0.1999*(prev) - 0.1360*(backlogs)
    const m = MODEL_STATS.regressionModel;
    let pred = m.intercept.est + (m.studyHours.est * study) + (m.prevSgpa.est * prev) + (m.backlogs.est * back);
    pred = Math.max(0, Math.min(10, pred)); // clamp to 0-10

    const predEl = document.getElementById("predResultSgpa");
    const riskBadge = document.getElementById("predRiskBadge");

    predEl.textContent = pred.toFixed(2);

    if (pred >= 8.0) {
      riskBadge.className = "badge badge-success";
      riskBadge.textContent = "High Achiever Tier (Dean's List Expected)";
    } else if (pred >= 6.75) {
      riskBadge.className = "badge badge-primary";
      riskBadge.textContent = "Stable / Satisfactory Standing";
    } else {
      riskBadge.className = "badge badge-danger";
      riskBadge.textContent = "At-Risk Standing (Academic Monitoring Advised)";
    }
  }

  [studySlider, prevSgpaSlider, backlogsSlider].forEach(s => {
    if (s) s.addEventListener("input", calcPrediction);
  });

  calcPrediction();
}

// Student Data Table
let currentPage = 1;
const rowsPerPage = 10;

function renderStudentTable() {
  const tbody = document.getElementById("studentTableBody");
  const search = (document.getElementById("tableSearch").value || "").toLowerCase();

  let list = filteredStudents.filter(s => {
    return (
      s.student_id.toString().includes(search) ||
      s.gender.toLowerCase().includes(search) ||
      s.degree_program.toLowerCase().includes(search) ||
      s.year_of_study.toLowerCase().includes(search) ||
      s.current_sgpa_range.toLowerCase().includes(search) ||
      s.academic_standing_risk.toLowerCase().includes(search)
    );
  });

  const totalRows = list.length;
  const totalPages = Math.ceil(totalRows / rowsPerPage) || 1;
  if (currentPage > totalPages) currentPage = 1;

  const start = (currentPage - 1) * rowsPerPage;
  const pageRows = list.slice(start, start + rowsPerPage);

  if (tbody) {
    if (pageRows.length === 0) {
      tbody.innerHTML = `<tr><td colspan="9" class="text-center py-6 text-slate-400">No students match current search and filter criteria.</td></tr>`;
    } else {
      tbody.innerHTML = pageRows.map(s => {
        let riskClass = "badge-success";
        if (s.academic_standing_risk === "High Risk") riskClass = "badge-danger";
        else if (s.academic_standing_risk === "Moderate Risk") riskClass = "badge-warning";

        let trajIcon = "↔";
        let trajColor = "#3b82f6";
        if (s.sgpa_trajectory === "Increased") { trajIcon = "↑"; trajColor = "#10b981"; }
        else if (s.sgpa_trajectory === "Decreased") { trajIcon = "↓"; trajColor = "#ef4444"; }

        return `<tr>
          <td class="font-mono text-slate-600">#${s.student_id}</td>
          <td>${s.gender}</td>
          <td>${s.year_of_study}</td>
          <td class="font-medium">${s.degree_program}</td>
          <td class="font-bold">${s.current_sgpa_range} <span style="color: ${trajColor}; font-weight:bold;">${trajIcon}</span></td>
          <td>${s.backlogs_category}</td>
          <td>${s.study_hours_original_range}</td>
          <td>${s.attendance_range}</td>
          <td><span class="badge ${riskClass}">${s.academic_standing_risk}</span></td>
        </tr>`;
      }).join("");
    }
  }

  // Pagination Controls
  const pageInfo = document.getElementById("tablePageInfo");
  if (pageInfo) {
    pageInfo.textContent = `Page ${currentPage} of ${totalPages} (${totalRows} records)`;
  }

  const prevBtn = document.getElementById("tablePrevBtn");
  const nextBtn = document.getElementById("tableNextBtn");
  if (prevBtn) prevBtn.disabled = currentPage <= 1;
  if (nextBtn) nextBtn.disabled = currentPage >= totalPages;
}

// Window table pagination hooks
window.changeTablePage = function(delta) {
  currentPage += delta;
  renderStudentTable();
};
