function buildHeatmapHtml(factorLabel, rowCategories, factorKey) {
  const sgpaCols = ["5-6", "6-7", "7-8", "8-9", "9-10"];
  
  // Calculate counts
  const matrix = {};
  const rowTotals = {};
  rowCategories.forEach(r => {
    matrix[r] = {};
    rowTotals[r] = 0;
    sgpaCols.forEach(c => matrix[r][c] = 0);
  });

  filteredStudents.forEach(s => {
    const r = s[factorKey];
    const c = s.current_sgpa_range;
    if (matrix[r] && matrix[r][c] !== undefined) {
      matrix[r][c]++;
      rowTotals[r]++;
    }
  });

  let html = `<table class="heatmap-table">
    <thead>
      <tr>
        <th class="factor-head">${factorLabel}</th>
        ${sgpaCols.map(c => `<th>SGPA ${c}</th>`).join("")}
        <th>Row Total</th>
      </tr>
    </thead>
    <tbody>`;

  rowCategories.forEach(r => {
    const total = rowTotals[r];
    html += `<tr><td class="row-label">${r}</td>`;
    sgpaCols.forEach(c => {
      const cnt = matrix[r][c];
      const pct = total > 0 ? ((cnt / total) * 100).toFixed(0) : 0;
      const alpha = total > 0 ? Math.min(1, Math.max(0.05, cnt / (total * 0.6))) : 0;
      const bgColor = cnt > 0 ? `rgba(37, 99, 235, ${alpha.toFixed(2)})` : "#f8fafc";
      const textColor = alpha > 0.5 ? "#ffffff" : "#1e293b";
      html += `<td style="background-color: ${bgColor}; color: ${textColor}; font-weight: 600;" title="${cnt} students (${pct}% of ${r})">
        ${cnt} <span class="pct-sub">(${pct}%)</span>
      </td>`;
    });
    html += `<td class="row-total">${total}</td></tr>`;
  });

  html += `</tbody></table>`;
  return html;
}

